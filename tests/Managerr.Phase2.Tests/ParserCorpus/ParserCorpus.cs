using System.Runtime.CompilerServices;
using System.Text.Encodings.Web;
using System.Text.Json;
using System.Text.Json.Nodes;
using Managerr.Downloaders.Parser;

namespace Managerr.Phase2.Tests.ParserCorpus;

/// <summary>One release name and what the parser must make of it.</summary>
/// <param name="Expect">Only the keys present are checked; a key with a null value must parse to null.</param>
public sealed record CorpusCase(string Id, string Release, string? Hint, JsonObject Expect, string Origin, string File);

public sealed record FieldMismatch(string Field, string Expected, string Actual)
{
    public override string ToString() => $"{Field}: expected {Expected}, got {Actual}";
}

/// <summary>
/// The release-name corpus: <c>managerr.jsonl</c> (hand-written, every parser regression goes here) plus
/// <c>upstream-*.jsonl</c> (generated by scripts/extract-upstream-parser-corpus.py from the Sonarr, Radarr and
/// Lidarr parser fixtures). Upstream cases Managerr does not parse yet are listed in <c>known-gaps.json</c>.
/// </summary>
public static class ParserCorpus
{
    public const string GapsFileName = "known-gaps.json";
    public const string UpdateGapsVariable = "MANAGERR_UPDATE_PARSER_GAPS";

    private static readonly Lazy<IReadOnlyList<CorpusCase>> LazyCases = new(LoadCases);
    private static readonly Lazy<IReadOnlyDictionary<string, KnownGap>> LazyGaps = new(LoadGaps);

    public static IReadOnlyList<CorpusCase> Cases => LazyCases.Value;

    private static readonly Lazy<Dictionary<string, CorpusCase>> LazyById = new(
        () => Cases.GroupBy(c => c.Id).ToDictionary(g => g.Key, g => g.First()));

    public static IReadOnlyDictionary<string, CorpusCase> ById => LazyById.Value;

    public static IReadOnlyDictionary<string, KnownGap> KnownGaps => LazyGaps.Value;

    public static string CorpusDirectory => Path.Combine(AppContext.BaseDirectory, "ParserCorpus");

    /// <summary>The checked-in folder, for rewriting known-gaps.json in place.</summary>
    public static string SourceDirectory([CallerFilePath] string thisFile = "") => Path.GetDirectoryName(thisFile)!;

    public static bool IsUpstream(string id) => !id.StartsWith("managerr/", StringComparison.Ordinal);

    private static List<CorpusCase> LoadCases()
    {
        var cases = new List<CorpusCase>();
        foreach (var file in Directory.EnumerateFiles(CorpusDirectory, "*.jsonl").Order(StringComparer.Ordinal))
        {
            var lineNo = 0;
            foreach (var line in File.ReadLines(file))
            {
                lineNo++;
                if (string.IsNullOrWhiteSpace(line) || line.StartsWith("//", StringComparison.Ordinal))
                {
                    continue;
                }

                var node = JsonNode.Parse(line) as JsonObject
                           ?? throw new InvalidDataException($"{Path.GetFileName(file)}:{lineNo} is not a JSON object");
                cases.Add(new CorpusCase(
                    Id: (string?)node["id"] ?? throw new InvalidDataException($"{Path.GetFileName(file)}:{lineNo} has no id"),
                    Release: (string?)node["release"] ?? throw new InvalidDataException($"{Path.GetFileName(file)}:{lineNo} has no release"),
                    Hint: (string?)node["hint"],
                    Expect: node["expect"] as JsonObject ?? [],
                    Origin: (string?)node["origin"] ?? "",
                    File: $"{Path.GetFileName(file)}:{lineNo}"));
            }
        }

        return cases;
    }

    // ---------------------------------------------------------------------------------------------------
    // Expectations
    // ---------------------------------------------------------------------------------------------------

    public static readonly IReadOnlyList<string> Fields =
    [
        "vertical", "title", "author", "year", "season", "episodes", "absolute", "seasonPack", "resolution", "source",
        "videoCodec", "hdr", "audio", "edition", "musicFormat", "bookFormat", "group", "dualAudio", "languagesInclude", "quality",
    ];

    /// <summary>The parsed value of one corpus field, as JSON, so expectations and parses compare uniformly.</summary>
    public static JsonNode? Actual(ParsedReleaseInfo p, string field) => field switch
    {
        "vertical" => p.MediaVertical,
        "title" => p.CleanTitle,
        "author" => p.ArtistOrAuthor,
        "year" => p.Year,
        "season" => p.SeasonNumber,
        "episodes" => new JsonArray(p.EpisodeNumbers.Select(e => (JsonNode)e).ToArray()),
        "absolute" => new JsonArray(p.AbsoluteEpisodeNumbers.Select(e => (JsonNode)e).ToArray()),
        "seasonPack" => p.IsFullSeasonPack,
        "resolution" => p.Resolution,
        "source" => p.Source,
        "videoCodec" => p.VideoCodec,
        "hdr" => p.HdrFormat,
        "audio" => p.AudioCodec,
        "edition" => p.MovieEdition,
        "musicFormat" => p.MusicFormat,
        "bookFormat" => p.BookFormat,
        "group" => p.ReleaseGroup,
        "dualAudio" => p.IsDualAudio,
        "languagesInclude" => new JsonArray(p.DetectedLanguages.Select(l => (JsonNode)l).ToArray()),
        "quality" => p.ToQualityName(),
        _ => throw new InvalidDataException($"Unknown corpus field '{field}'. Known: {string.Join(", ", Fields)}"),
    };

    public static string NormalizeTitleForCompare(string? title) =>
        title is null ? string.Empty : new string(title.Where(char.IsLetterOrDigit).Select(char.ToLowerInvariant).ToArray());

    public static IReadOnlyList<FieldMismatch> Check(ParsedReleaseInfo parsed, JsonObject expect)
    {
        var mismatches = new List<FieldMismatch>();
        foreach (var (field, expected) in expect)
        {
            var actual = Actual(parsed, field);
            var ok = field switch
            {
                "languagesInclude" => expected!.AsArray().All(l => actual!.AsArray().Any(a => (string?)a == (string?)l)),
                "title" when expected is not null && actual is not null =>
                    NormalizeTitleForCompare((string?)expected) == NormalizeTitleForCompare((string?)actual),
                _ => JsonNode.DeepEquals(expected, actual),
            };
            if (!ok)
            {
                mismatches.Add(new FieldMismatch(field, Show(expected), Show(actual)));
            }
        }

        return mismatches;
    }

    private static readonly JsonSerializerOptions ShowOptions = new() { Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping };

    public static string Show(JsonNode? node) => node is null ? "null" : node.ToJsonString(ShowOptions);

    // ---------------------------------------------------------------------------------------------------
    // Known gaps: upstream cases (and metamorphic variants, id#variant) the parser does not handle yet
    // ---------------------------------------------------------------------------------------------------

    public sealed record KnownGap(string Release, IReadOnlyList<string> Fields);

    private static Dictionary<string, KnownGap> LoadGaps()
    {
        var path = Path.Combine(CorpusDirectory, GapsFileName);
        if (!File.Exists(path))
        {
            return [];
        }

        var root = JsonNode.Parse(File.ReadAllText(path))!.AsObject();
        return root.Where(kv => !kv.Key.StartsWith("//", StringComparison.Ordinal)).ToDictionary(
            kv => kv.Key,
            kv => new KnownGap((string)kv.Value!["release"]!, kv.Value!["fields"]!.AsArray().Select(f => (string)f!).ToArray()));
    }

    /// <summary>
    /// Judges an evaluation against the baseline: a key not in known-gaps.json must pass; a known gap must fail
    /// on exactly the recorded fields, so both a fix (time to shrink the baseline) and a new breakage show up.
    /// Returns the failure message, or null.
    /// </summary>
    public static string? Verdict(Evaluation e)
    {
        var failing = e.FailingFields;
        if (!KnownGaps.TryGetValue(e.Key, out var gap))
        {
            return failing.Count == 0 ? null : $"'{e.Release}' ({e.Key}) misparsed:\n  {string.Join("\n  ", e.Mismatches)}";
        }

        if (failing.SequenceEqual(gap.Fields.Order(StringComparer.Ordinal)))
        {
            return null;
        }

        return failing.Count == 0
            ? $"'{e.Release}' ({e.Key}) now parses correctly. Remove it from {GapsFileName} (or rerun with {UpdateGapsVariable}=1)."
            : $"'{e.Release}' ({e.Key}) is a known gap on [{string.Join(", ", gap.Fields)}] but now fails on [{string.Join(", ", failing)}]:\n  " +
              string.Join("\n  ", e.Mismatches);
    }

    // ---------------------------------------------------------------------------------------------------
    // Evaluation: direct expectations and metamorphic variants
    // ---------------------------------------------------------------------------------------------------

    public sealed record Evaluation(string Key, string Release, IReadOnlyList<FieldMismatch> Mismatches)
    {
        public IReadOnlyList<string> FailingFields { get; } = Mismatches.Select(m => m.Field).Distinct().Order(StringComparer.Ordinal).ToArray();
    }

    /// <summary>
    /// A rewrite of a release name that must not change what is parsed out of it. Indexers and download clients
    /// hand the same release over dotted, underscored or lower-cased, and each spelling must land on the same work.
    /// </summary>
    public sealed record Variant(string Name, Func<string, string?> Rewrite, IReadOnlyList<string> Fields);

    private static readonly string[] IdentityFields = ["vertical", "title", "author", "year", "season", "episodes", "absolute", "seasonPack"];

    public static readonly IReadOnlyList<Variant> Variants =
    [
        // 'Series.Title.S01E02.1080p' -> 'Series_Title_S01E02_1080p' (only pure scene-dotted names: spaces/underscores already mean something)
        new("underscored", r => r.Contains('.') && !r.Contains(' ') && !r.Contains('_') ? r.Replace('.', '_') : null, IdentityFields),
        // nzb and file names are often lower-cased; the title then differs in case only, numbers and tags must not
        new("lowercased", r => r.Any(char.IsUpper) ? r.ToLowerInvariant() : null,
            ["vertical", "year", "season", "episodes", "absolute", "seasonPack", "resolution", "source"]),
    ];

    public static ParsedReleaseInfo Parse(string release, string? hint) => new ReleaseParserRouter().Parse(release, hint);

    public static Evaluation Evaluate(CorpusCase c) => new(c.Id, c.Release, Check(Parse(c.Release, c.Hint), c.Expect));

    /// <summary>The variant of <paramref name="c"/> compared field by field with the original's parse, or null when it does not apply.</summary>
    public static Evaluation? Evaluate(CorpusCase c, Variant v)
    {
        var rewritten = v.Rewrite(c.Release);
        if (rewritten is null || rewritten == c.Release)
        {
            return null;
        }

        var original = Parse(c.Release, c.Hint);
        var variant = Parse(rewritten, c.Hint);
        var mismatches = new List<FieldMismatch>();
        foreach (var field in v.Fields)
        {
            var expected = Actual(original, field);
            var actual = Actual(variant, field);
            var ok = field == "title" && expected is not null && actual is not null
                ? NormalizeTitleForCompare((string?)expected) == NormalizeTitleForCompare((string?)actual)
                : JsonNode.DeepEquals(expected, actual);
            if (!ok)
            {
                mismatches.Add(new FieldMismatch(field, Show(expected), Show(actual)));
            }
        }

        return new Evaluation($"{c.Id}#{v.Name}", rewritten, mismatches);
    }

    /// <summary>Cases with expectations (the CrapParserFixture inputs only feed the invariant tests).</summary>
    public static IEnumerable<CorpusCase> CasesWithExpectations => Cases.Where(c => c.Expect.Count > 0);

    public static IEnumerable<Evaluation> EvaluateAll()
    {
        foreach (var c in CasesWithExpectations)
        {
            yield return Evaluate(c);
            foreach (var v in Variants)
            {
                if (Evaluate(c, v) is { } e)
                {
                    yield return e;
                }
            }
        }
    }

    /// <summary>Rewrites known-gaps.json in the source tree from what the parser does today.</summary>
    public static int WriteKnownGaps(string directory)
    {
        var gaps = new JsonObject
        {
            ["// generated"] = $"Corpus cases the parser does not handle yet. Regenerate with {UpdateGapsVariable}=1 dotnet test --filter ParserCorpus. Shrink it, never grow it by hand.",
        };
        var count = 0;
        foreach (var e in EvaluateAll().Where(e => e.FailingFields.Count > 0).OrderBy(e => e.Key, StringComparer.Ordinal))
        {
            gaps[e.Key] = new JsonObject
            {
                ["release"] = e.Release,
                ["fields"] = new JsonArray(e.FailingFields.Select(f => (JsonNode)f).ToArray()),
            };
            count++;
        }

        File.WriteAllText(
            Path.Combine(directory, GapsFileName),
            gaps.ToJsonString(new JsonSerializerOptions { WriteIndented = true, Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping }) + "\n");
        return count;
    }
}
